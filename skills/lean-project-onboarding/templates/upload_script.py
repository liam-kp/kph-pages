def load_token():
    if not TOKEN_PATH.exists():
        sys.exit(f"❌ Token file not found at {TOKEN_PATH}. Refresh per KPR-50 procedure.")
    token = TOKEN_PATH.read_text().strip()
    if not token.startswith("Bearer "):
        token = "Bearer " + token
    return token

def request(method, path, body=None):
    """Single HTTP helper. All requests go through here so the User-Agent is consistent."""
    url = f"{API_BASE}/{path}?customerId={CUSTOMER_ID}"
    headers = {
        "Authorization": TOKEN,
        "Content-Type": "application/json",
        "User-Agent": USER_AGENT,
    }
    data = None
    if body is not None:
        data = json.dumps(body).encode("utf-8")
    req = urllib.request.Request(url, data=data, method=method, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=60) as resp:
            return resp.status, resp.read().decode("utf-8", errors="replace")
    except urllib.error.HTTPError as e:
        body_text = e.read().decode("utf-8", errors="replace")
        return e.code, body_text
    except urllib.error.URLError as e:
        return 0, f"NETWORK_ERROR: {e}"

def diagnose_error(status, response_text):
    """Map common errors to actionable advice."""
    if status == 401:
        return "TOKEN EXPIRED (KPR-50). Refresh from app.aiagentpro.online > DevTools console:\n   JSON.parse(localStorage.getItem('auth-storage')).state.token"
    if status == 403 and "1010" in response_text:
        return "CLOUDFLARE BLOCKED (error 1010). User-Agent should already be set — check this script."
    if status == 403:
        return "FORBIDDEN. Possibly running from Cowork sandbox (egress blocked). Run from Mac terminal."
    if status == 500 and "default Firebase app does not exist" in response_text:
        return "KPR-92 OPEN BUG — server-side Firebase init failure. Adam needs to fix. Workaround: manual upload via app.aiagentpro.online/dashboard"
    if status == 0:
        return f"NETWORK ERROR. Check internet connection. {response_text}"
    return None

def encode_image_to_base64(path):
    if not path.exists():
        sys.exit(f"❌ Image not found: {path}")
    with open(path, "rb") as f:
        return base64.b64encode(f.read()).decode("ascii")

def now_iso():
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.%fZ")

def now_date():
    return datetime.now(timezone.utc).strftime("%Y-%m-%d")

