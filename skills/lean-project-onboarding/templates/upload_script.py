    ("03_bedroom_master.jpg", f"KP-IMG-{PROJECT_ID.split('-')[1]}-{PROJECT_ID.split('-')[2]}-PING1-03"),
    ("04_living.jpg",         f"KP-IMG-{PROJECT_ID.split('-')[1]}-{PROJECT_ID.split('-')[2]}-PING1-04"),
