for sort_order, (filename, image_id) in enumerate(PING1_IMAGES, start=1):
    image_path = IMAGES_FOLDER / filename
    image_b64 = encode_image_to_base64(image_path)
    mime, _ = mimetypes.guess_type(filename)
    if not mime:
        mime = "image/jpeg"
    size = image_path.stat().st_size
    total_bytes += size

    payload = {
        "_id": image_id,
        "image_id": image_id,
        "project_id": PROJECT_ID,
        "customerId": CUSTOMER_ID,
        "file_name": filename,
        "filename": filename,
        "mime_type": mime,
        "is_ping1": True,
        "is_primary": (sort_order == 1),
        "sort_order": sort_order,
        "image_data": image_b64,
        "uploaded_at": now_iso(),
    }

    status, body = request("PUT", f"Project_Images/{image_id}", body=payload)
    print(f"  PUT  {image_id}  [{size:,} bytes]  →  HTTP {status}")
    if status != 200:
        diag = diagnose_error(status, body)
        if diag:
            print(f"     >>> {diag}")
        print(f"     response: {body[:300]}")

    # Verify with GET
    g_status, g_body = request("GET", f"Project_Images/{image_id}")
    verified = (g_status == 200 and image_id in g_body)
    print(f"  GET  {image_id}  →  HTTP {g_status}  verified={verified}")

    image_results.append({
        "image_id": image_id,
        "put_status": status,
        "get_status": g_status,
        "verified": verified,
        "size": size,
    })

